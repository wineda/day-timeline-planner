export function monsterByName(name: string): Monster | undefined {
  const n = name.trim();
  return MONSTERS.find((m) => m.name === n);
}

/** FNV-1a。プロジェクト名から毎回同じモンスターを選ぶための小さなハッシュ */
function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h;
}

/** そのランクの中から、種（プロジェクトのリンク先）で決まる1体を選ぶ。offset で「別の姿」に順に切り替えられる */
export function pickMonster(seed: string, rank: MonsterRank, offset = 0): Monster {
  const pool = MONSTERS.filter((m) => m.rank === rank);
  return pool[(hash(seed) + offset) % pool.length];
}

/** 「- 難易度: 」の値をランクにする（雑魚 / 中級 / ボス、★の数、1〜3 も読む）。読めなければ null */
export function parseRank(v: string): MonsterRank | null {
  const t = v.trim();
  if (!t) return null;
  if (t === "雑魚" || t === "★" || t === "1" || /^(easy|low)$/i.test(t)) return "雑魚";
  if (t === "中級" || t === "★★" || t === "2" || /^(normal|mid|medium)$/i.test(t)) return "中級";
  if (t === "ボス" || t === "★★★" || t === "3" || /^(boss|hard|high)$/i.test(t)) return "ボス";
  return null;
}

/** 予定時間の合計（時間）からランクを決める */
export function rankForHours(hours: number, midHours: number, bossHours: number): MonsterRank {
  if (bossHours > 0 && hours >= bossHours) return "ボス";
  if (midHours > 0 && hours >= midHours) return "中級";
  return "雑魚";
}

function expand(rows: string[], n: number): string[] {
  return rows.map((r) => (r.length === n ? r : r + [...r].reverse().join("")));
}

/** 体の周りに輪郭（o）を付ける */
function outline(g: string[], n: number): string[][] {
  const solid = (c: string | undefined) => !!c && c !== "." && c !== "o";
  const out = g.map((r) => [...r]);
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (solid(g[y][x])) continue;
      const near = [
        [0, 1],
        [1, 0],
        [0, -1],
        [-1, 0],
      ].some(([dx, dy]) => solid(g[y + dy]?.[x + dx]));
      if (near) out[y][x] = "o";
    }
  }
  return out;
}

/**
 * ピクセルアート用の EPX（Scale2x）でグリッドを2倍に拡大する。
 * 上下左右の色を見て斜めの段差の角を埋めるので、同じドット絵でも解像度を上げたようになめらかになる
 */
function scale2x(g: (string | null)[][]): (string | null)[][] {
  const h = g.length;
  const w = g[0]?.length ?? 0;
  const out: (string | null)[][] = Array.from({ length: h * 2 }, () => new Array<string | null>(w * 2).fill(null));
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const p = g[y][x];
      const up = y > 0 ? g[y - 1][x] : null;
      const right = x + 1 < w ? g[y][x + 1] : null;
      const left = x > 0 ? g[y][x - 1] : null;
      const down = y + 1 < h ? g[y + 1][x] : null;
      const row0 = out[y * 2];
      const row1 = out[y * 2 + 1];
      row0[x * 2] = left === up && left !== down && up !== right ? up : p;
      row0[x * 2 + 1] = up === right && up !== left && right !== down ? right : p;
      row1[x * 2] = down === left && down !== right && left !== up ? left : p;
      row1[x * 2 + 1] = right === down && right !== up && down !== left ? down : p;
    }
  }
  return out;
}

function gray(c: string): string {
  const v = parseInt(c.slice(1), 16);
  const l = Math.round((v >> 16) * 0.3 + ((v >> 8) & 255) * 0.59 + (v & 255) * 0.11);
  return "#" + ((l << 16) | (l << 8) | l).toString(16).padStart(6, "0");
}

/**
 * モンスターを SVG の文字列にする。
 * hp は残り HP の割合（0〜1）。50% 以下で汗と波打つ口、20% 以下で「><」の目、0 で灰色になって横倒し
 */
export function monsterSVG(m: Monster, hp: number, size: number): string {
  const n = RANK_GRID[m.rank];
  const px = size / n;
  const g = outline(expand(m.rows, n), n);
  const defeated = hp <= 0;
  const hurt = hp <= 0.5 && !defeated;
  const critical = hp <= 0.2 && !defeated;
  const col = (c: string) => (defeated ? gray(c) : c);
  const eyes: [number, number][] = [];
  const mouth: [number, number][] = [];
  const cells: [number, number][] = [];
  // シンボルを色に直してから EPX で2倍に拡大する。目・口・汗などの飾りは元のドット座標のまま重ねる
  const colors = g.map((row, y) =>
    row.map((ch, x): string | null => {
      let c = ch;
      if (c === ".") return null;
      if (c === "e") {
        eyes.push([x, y]);
        c = "#";
      } else if (c === "m") {
        mouth.push([x, y]);
        if (hurt || defeated) c = "#";
      }
      if (c === "#" && y > n / 2) cells.push([x, y]);
      return m.pal[c] ?? m.pal["#"];
    })
  );
  const hi = scale2x(colors);
  const hpx = px / 2;
  let body = "";
  hi.forEach((row, y) => {
    // 同じ色の横並びは1つの rect にまとめて、SVG が大きくなり過ぎないようにする
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      if (!c) {
        x++;
        continue;
      }
      let x2 = x + 1;
      while (x2 < row.length && row[x2] === c) x2++;
      body += `<rect x="${x * hpx}" y="${y * hpx}" width="${(x2 - x) * hpx}" height="${hpx}" fill="${col(c)}"/>`;
      x = x2;
    }
  });
  const dark = col(m.pal.o);
  for (const [x, y] of eyes) {
    const X = x * px;
    const Y = y * px;
    if (defeated) {
      body += `<path d="M${X},${Y} l${px},${px} M${X + px},${Y} l${-px},${px}" stroke="${dark}" stroke-width="${px / 3}"/>`;
    } else if (critical) {
      const d = x < n / 2 ? 1 : -1;
      body += `<path d="M${X + (d > 0 ? 0 : px)},${Y} l${d * px},${px / 2} l${-d * px},${px / 2}" fill="none" stroke="${dark}" stroke-width="${px / 3}"/>`;
    } else {
      const pupil = m.rank === "ボス" ? col(m.pal.r) : dark;
      body += `<rect x="${X}" y="${Y}" width="${px}" height="${px}" fill="#fff"/><rect x="${X + px / 2}" y="${Y + (hurt ? px / 2 : px / 4)}" width="${px / 2}" height="${px / 2}" fill="${pupil}"/>`;
    }
  }
  if (mouth.length && (hurt || defeated)) {
    const xs = mouth.map((p) => p[0]);
    const y = mouth[0][1] * px + px / 2;
    const x0 = Math.min(...xs) * px;
    const x1 = (Math.max(...xs) + 1) * px;
    const w = (x1 - x0) / 4;
    let d = `M${x0},${y}`;
    for (let i = 0; i < 4; i++) d += ` l${w / 2},${i % 2 ? px / 2 : -px / 2} l${w / 2},${i % 2 ? -px / 2 : px / 2}`;
    body += `<path d="${d}" fill="none" stroke="${dark}" stroke-width="${px / 3}"/>`;
  }
  if (!defeated && hp < 0.8 && cells.length) {
    const k = hp < 0.2 ? 3 : hp < 0.5 ? 2 : 1;
    for (let i = 0; i < k; i++) {
      const [x, y] = cells[Math.floor(cells.length * ((i + 1) / (k + 1)))];
      const X = x * px;
      const Y = y * px;
      body += `<path d="M${X + px * 0.2},${Y} l${px * 0.5},${px * 0.6} l${-px * 0.3},${px * 0.5}" fill="none" stroke="${dark}" stroke-width="${px / 4}" stroke-linecap="round"/>`;
    }
  }
  if (hurt) {
    body += `<path d="M${(n - 2) * px},${2 * px} q${px},${px * 1.5} 0,${px * 2.2} q${-px},${-px * 0.7} 0,${-px * 2.2}z" fill="#7dd3fc" stroke="#0369a1" stroke-width="${px / 4}"/>`;
  }
  let aura = "";
  if (m.rank === "ボス" && !defeated) {
    // 同じ画面に複数のボスが居ても gradient の id が衝突しないよう、名前から作る
    const id = "dt-aura-" + hash(m.name).toString(36);
    aura =
      `<defs><radialGradient id="${id}"><stop offset="0" stop-color="${m.pal.a}" stop-opacity="0.5"/><stop offset="1" stop-color="${m.pal.a}" stop-opacity="0"/></radialGradient></defs>` +
      `<circle cx="${size / 2}" cy="${size * 0.55}" r="${size * 0.5}" fill="url(#${id})"/>`;
  }
  const tf = defeated ? ` transform="rotate(90 ${size / 2} ${size / 2})"` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}" role="img"><g shape-rendering="crispEdges"${tf}>${aura}${body}</g></svg>`;
}
